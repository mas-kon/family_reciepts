MANUAL_SYSTEM = """\
Пользователь записывает трату одной строкой: название и сумма. Все суммы в евро.
Верни ТОЛЬКО JSON: {"name": "...", "amount": 0.00, "category": "..."}
name: что купили, с заглавной буквы.
category: одна категория из списка, дословно.

Категории:
{categories}
"""


def categories_block(paths: list[str]) -> str:
    return "\n".join(f"- {p}" for p in paths)


def receipt_system(paths: list[str]) -> str:
    return RECEIPT_SYSTEM.replace("{categories}", categories_block(paths))


def manual_system(paths: list[str]) -> str:
    return MANUAL_SYSTEM.replace("{categories}", categories_block(paths))


